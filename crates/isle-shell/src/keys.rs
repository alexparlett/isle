//! Keys as Freya names them: xkb keysyms to keys, evdev codes to physical codes.

use freya::prelude::{Code, Key, Modifiers, NamedKey};
use smithay::input::keyboard::{ModifiersState, xkb::Keysym};

pub fn key(keysym: Keysym, text: Option<String>) -> Key {
    let named = match keysym {
        Keysym::BackSpace => NamedKey::Backspace,
        Keysym::Return | Keysym::KP_Enter => NamedKey::Enter,
        Keysym::Tab | Keysym::ISO_Left_Tab => NamedKey::Tab,
        Keysym::Escape => NamedKey::Escape,
        Keysym::Delete | Keysym::KP_Delete => NamedKey::Delete,
        Keysym::Insert | Keysym::KP_Insert => NamedKey::Insert,
        Keysym::Left | Keysym::KP_Left => NamedKey::ArrowLeft,
        Keysym::Right | Keysym::KP_Right => NamedKey::ArrowRight,
        Keysym::Up | Keysym::KP_Up => NamedKey::ArrowUp,
        Keysym::Down | Keysym::KP_Down => NamedKey::ArrowDown,
        Keysym::Home | Keysym::KP_Home => NamedKey::Home,
        Keysym::End | Keysym::KP_End => NamedKey::End,
        Keysym::Page_Up | Keysym::KP_Page_Up => NamedKey::PageUp,
        Keysym::Page_Down | Keysym::KP_Page_Down => NamedKey::PageDown,
        Keysym::Shift_L | Keysym::Shift_R => NamedKey::Shift,
        Keysym::Control_L | Keysym::Control_R => NamedKey::Control,
        Keysym::Alt_L | Keysym::Alt_R => NamedKey::Alt,
        Keysym::Super_L | Keysym::Super_R | Keysym::Meta_L | Keysym::Meta_R => NamedKey::Meta,
        Keysym::Caps_Lock => NamedKey::CapsLock,
        Keysym::Num_Lock => NamedKey::NumLock,
        Keysym::Menu => NamedKey::ContextMenu,
        Keysym::F1 => NamedKey::F1,
        Keysym::F2 => NamedKey::F2,
        Keysym::F3 => NamedKey::F3,
        Keysym::F4 => NamedKey::F4,
        Keysym::F5 => NamedKey::F5,
        Keysym::F6 => NamedKey::F6,
        Keysym::F7 => NamedKey::F7,
        Keysym::F8 => NamedKey::F8,
        Keysym::F9 => NamedKey::F9,
        Keysym::F10 => NamedKey::F10,
        Keysym::F11 => NamedKey::F11,
        Keysym::F12 => NamedKey::F12,
        _ => match text {
            Some(text) if !text.is_empty() && !text.chars().any(char::is_control) => {
                return Key::Character(text);
            }
            _ => NamedKey::Unidentified,
        },
    };
    Key::Named(named)
}

/// The held modifiers only, as winit reports them: Freya reads a lock as a held key, and Tab
/// with Num Lock on would not move focus.
pub fn modifiers(state: &ModifiersState) -> Modifiers {
    let mut modifiers = Modifiers::empty();
    modifiers.set(Modifiers::SHIFT, state.shift);
    modifiers.set(Modifiers::CONTROL, state.ctrl);
    modifiers.set(Modifiers::ALT, state.alt);
    modifiers.set(Modifiers::META, state.logo);
    modifiers
}

